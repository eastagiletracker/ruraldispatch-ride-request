/**
 * Helper functions
 */
export const isRideRequestClosingStatus = (status: number): boolean => {
  return RIDE_REQUEST_CLOSING_STATUSES.includes(status as any);
};

export const isRideRequestProblematicStatus = (status: number): boolean => {
  return RIDE_REQUEST_PROBLEMATIC_STATUSES.includes(status as any);
};

export const isValidRideRequestStatus = (status: number): boolean => {
  return (Object.values(RIDE_REQUEST_STATUSES) as number[]).includes(status);
};

export const getRideRequestStatusDescription = (status: number): string => {
  return RIDE_REQUEST_STATUS_DESCRIPTIONS[status] || 'Unknown Status';
};

export const getNextValidRideRequestStatuses = (currentStatus: number): number[] => {
  return RIDE_REQUEST_STATUS_TRANSITIONS[currentStatus] || [];
};

export const isValidRideRequestStatusTransition = (
  fromStatus: number,
  toStatus: number
): boolean => {
  const validNextStatuses = getNextValidRideRequestStatuses(fromStatus);
  return validNextStatuses.includes(toStatus);
};

/**
 * TypeScript types
 */
export type RideRequestStatus = (typeof RIDE_REQUEST_STATUSES)[keyof typeof RIDE_REQUEST_STATUSES];
export type RideRequestStatusCategory = keyof typeof RIDE_REQUEST_STATUS_CATEGORIES;
